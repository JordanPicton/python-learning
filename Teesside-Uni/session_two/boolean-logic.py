# Boolean Logic
print("The Hello is valued as a", type("Hello"), "data type.")
print("5 is valued as a", type(5), "data type.")
print("False is valued as a", type(False), "data type.")
print("True AND True result in a", True and True, "output.")
print("True AND False result in a", True and False, "output.")
print("True OR False result in a", True or False, "output.")
print("True OR True result in a", True or True, "output.")
print("False OR False result in a", False or False, "output.")
print("NOT True is", not True)
print("NOT False is", not False)
print("NOT NOT NOT NOT True is", not not not not True)

